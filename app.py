class Handler(BaseHTTPRequestHandler):
    def do_GET(self) -> None:
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/":
            self._send(200, render(), "text/html; charset=utf-8")
            return
        if parsed.path == "/health":
            self._send(
                200,
                json.dumps({"ok": True, "documents": PIPELINE.ensure_index()}),
                "application/json",
            )
            return
        if parsed.path == "/ask":
            question = urllib.parse.parse_qs(parsed.query).get("q", [""])[0]
            self._answer(question)
            return
        self._send(404, "Not found", "text/plain; charset=utf-8")

    def _answer(self, question: str) -> None:
        if not question.strip():
            self._send(400, render(error="Enter a question."), "text/html; charset=utf-8")
            return
        try:
            result = PIPELINE.ask(question)
        except Exception as exc:
            self._send(502, render(error=str(exc)), "text/html; charset=utf-8")
            return
        self._send(200, render(result), "text/html; charset=utf-8")

    def _send(self, status: int, body: str, content_type: str) -> None:
        encoded = body.encode()
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(encoded)))
        self.end_headers()
        self.wfile.write(encoded)

    def log_message(self, fmt: str, *args) -> None:
        print(f"[{self.address_string()}] {fmt % args}")


def main() -> None:
    count = PIPELINE.ensure_index()
    print(f"Index ready: {count} documents")
    print(f"Open http://{HOST}:{PORT}")
    server = ThreadingHTTPServer((HOST, PORT), Handler)
    server.serve_forever()


if __name__ == "__main__":
    main()
