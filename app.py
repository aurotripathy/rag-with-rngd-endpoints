"""Small web UI for the RNGD sample RAG pipeline."""

from __future__ import annotations

import html
import json
import os
import urllib.parse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from rag import CORPUS, Pipeline

HOST = os.environ.get("RAG_HOST", "127.0.0.1")
PORT = int(os.environ.get("RAG_PORT", "8765"))
PIPELINE = Pipeline()

EXAMPLES = [
    "How do I search vectors in Postgres?",
    "What is RAG?",
    "What is the capital of France?",
]


def _hits(title: str, note: str, hits) -> str:
    rows = []
    for rank, hit in enumerate(hits, start=1):
        rows.append(
            "<li><span class='score'>"
            f"{hit.score:.4f}</span> "
            f"<span class='rank'>{rank}.</span> {html.escape(hit.text)}</li>"
        )
    return (
        f"<section><h2>{html.escape(title)}</h2>"
        f"<p class='note'>{html.escape(note)}</p><ol>{''.join(rows)}</ol></section>"
    )


